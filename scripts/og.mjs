// Imagen para compartir (E17, spec §9: el enlace se ve bien en WhatsApp): 1200 × 630, compuesta
// como el hero con los colores de src/styles/global.css, los textos de src/i18n/es.json, Poppins
// y la ilustración de Don Pascal. Se vuelve a ejecutar si cambian la paleta, el titular o él.
// Uso: node scripts/og.mjs   (Playwright y ImageMagick, como scripts/imagenes.sh)
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from 'playwright-core';

const raiz = resolve(import.meta.dirname, '..');
const archivo = (ruta) => pathToFileURL(join(raiz, ruta)).href;

// Los colores salen de :root, nunca escritos aquí
const css = readFileSync(join(raiz, 'src/styles/global.css'), 'utf8');
const color = (nombre) => css.match(new RegExp(`--${nombre}:\\s*(#[0-9a-f]{6})`, 'i'))?.[1] ?? (() => { throw new Error(`falta --${nombre}`); })();
const textos = JSON.parse(readFileSync(join(raiz, 'src/i18n/es.json'), 'utf8'));
const fuente = (peso) => archivo(`node_modules/@fontsource/poppins/files/poppins-latin-${peso}-normal.woff2`);

const html = `<!doctype html><html lang="es"><head><meta charset="utf-8"><style>
  ${[300, 400, 700].map((p) => `@font-face{font-family:Poppins;font-weight:${p};src:url(${fuente(p)}) format('woff2')}`).join('')}
  *{margin:0;box-sizing:border-box}
  body{width:1200px;height:630px;overflow:hidden;background:${color('monte')};font-family:Poppins;color:${color('papel')};position:relative}
  .marca{position:absolute;left:72px;top:56px;display:flex;align-items:center;gap:16px;font-weight:700;font-size:30px;letter-spacing:-0.02em}
  .marca img{width:56px;height:56px;border-radius:50%;background:${color('monte-claro')}}
  h1{position:absolute;left:72px;top:170px;font-size:70px;line-height:1.05;letter-spacing:-0.03em}
  h1 span{display:block}
  .ligero{font-weight:300;color:${color('pradera')}}
  .apoyo{position:absolute;left:72px;top:352px;width:600px;font-size:25px;line-height:1.45;color:${color('sobre-monte-suave')}}
  .aviso{position:absolute;left:72px;bottom:48px;width:600px;font-size:19px;line-height:1.45;color:${color('sobre-monte-suave')}}
  .arco{position:absolute;right:70px;bottom:0;width:350px;height:500px;border-radius:175px 175px 0 0;background:${color('monte-claro')}}
  .pascal{position:absolute;right:60px;top:70px;height:640px}
</style></head><body>
  <div class="marca"><img src="${archivo('public/img/avatar-224.webp')}" alt="">${textos['sitio.nombre']}</div>
  <h1><span>${textos['hero.titulo-fuerte']}</span><span class="ligero">${textos['hero.titulo-ligero']}</span></h1>
  <p class="apoyo">${textos['hero.apoyo']}</p>
  <p class="aviso">${textos['aviso.concepto']}</p>
  <div class="arco"></div>
  <img class="pascal" src="${archivo('src/assets/don-pascal/cuerpo-entero.png')}" alt="">
</body></html>`;

const tmp = mkdtempSync(join(tmpdir(), 'og-'));
const pagina = join(tmp, 'og.html');
writeFileSync(pagina, html);

const navegador = await chromium.launch();
const p = await navegador.newPage({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
await p.goto(pathToFileURL(pagina).href, { waitUntil: 'load' });
await p.evaluate(() => document.fonts.ready);
const png = join(tmp, 'og.png');
await p.screenshot({ path: png });
await navegador.close();

// JPEG para que pese poco (WhatsApp descarta las grandes) y con su procedencia (ASCII: si no, se pierde)
const salida = join(raiz, 'public/og/don-pascal.jpg');
execFileSync('magick', [png, '-strip', '-quality', '86', '-set', 'comment', 'impeccable:prompt: Composed by scripts/og.mjs from the shop tokens, texts and the AI illustration of Don Pascal (generated by the user with Nano Banana, 2026-11-14).', salida]);
console.log(`Listo: ${salida}`);
